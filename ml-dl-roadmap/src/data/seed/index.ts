function task(
  weekNumber: number,
  order: number,
  partial: Partial<Omit<Task, 'id' | 'createdAt' | 'updatedAt' | 'weekNumber' | 'order'>> &
    Pick<Task, 'title' | 'description' | 'track' | 'type' | 'estimatedMinutes' | 'difficulty' | 'status' | 'completionCriteria'>,
): Task {
  return {
    id: createId(),
    weekNumber,
    order,
    actualMinutes: partial.actualMinutes ?? 0,
    notes: partial.notes ?? '',
    evidenceIds: partial.evidenceIds ?? [],
    prerequisites: partial.prerequisites ?? [],
    relatedResources: partial.relatedResources ?? [],
    interviewConcepts: partial.interviewConcepts ?? [],
    title: partial.title,
    description: partial.description,
    track: partial.track,
    type: partial.type,
    projectId: partial.projectId,
    estimatedMinutes: partial.estimatedMinutes,
    difficulty: partial.difficulty,
    status: partial.status,
    completionCriteria: partial.completionCriteria,
    deliverable: partial.deliverable,
    commonMistake: partial.commonMistake,
    scheduledDate: partial.scheduledDate,
    completedAt: partial.completedAt,
    parentTaskId: partial.parentTaskId,
    deferred: partial.deferred,
    deferredReason: partial.deferredReason,
    ...ts(),
  }
}

